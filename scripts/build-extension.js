import { readFile, writeFile } from "node:fs/promises";

const directory = new URL("../browser/iq-option-reader/", import.meta.url);
const sources = ["normalized-market-data.js", "collector.js", "debug-panel.js", "content-script.js"];
const parts = [];

for (const source of sources) {
  let code = await readFile(new URL(source, directory), "utf8");
  code = code
    .replace(/import\s+\{[\s\S]*?\}\s+from\s+"[^"]+";\s*/g, "")
    .replace(/export\s+(?=(const|class|function)\b)/g, "");
  parts.push(`// Source: ${source}\n${code.trim()}`);
}

const banner = "// Generated by npm run build:extension. Do not edit directly.\n(() => {\n\"use strict\";\n";
await writeFile(new URL("content-script.bundle.js", directory), `${banner}${parts.join("\n\n")}\n})();\n`);
